import pandas as pd
import numpy as np


df = pd.read_csv("inpatient_multitask_surveillance.csv")

df.head()

features =['age', 'gender','admission_ward','charlson_comorbidity_index','frailty_score_tier','mobility_status','primary_antibiotic_class','abx_duration_days','ppi_exposure_days','nephrotoxic_drug_count','serum_albumin_g_dl','wbc_count_k_ul','baseline_creatinine_mg_dl','systolic_bp_mmhg']
X = df[features]
targets = ['cdi_infection_flag','readmission_30d_flag','acute_kidney_injury_flag']
y = df[targets]

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit(n_splits =1, test_size = 0.2, random_state = 42)
for train_index, test_index in split.split(X,y):
  X_train, X_test = X.iloc[train_index], X.iloc[test_index]
  y_train, y_test = y.iloc[train_index],y.iloc[test_index]

df.primary_antibiotic_class.value_counts()

gender_status = ['Male','Female']

ward_count = ['General Medical','Surgical','Geriatric Care','Oncology','ICU Stepdown']

frailty_status = ['Fit / Robust','Mild Frailty','Moderate Frailty','Severe Frailty']

mobility_index =['Independent','Assisted','Bedbound']

antibiotic_status =['Macrolide', 'Penicillin/BLI','Fluoroquinolone','Carbapenem','Cephalosporin (3rd/4th Gen)']

cat_cols = ['frailty_score_tier','mobility_status']

cat_categories = [frailty_status,mobility_index]


nom_categories = [gender_status, ward_count,antibiotic_status]

nom_cols = ['gender', 'admission_ward','primary_antibiotic_class']



from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, OrdinalEncoder


cat_encoder = OrdinalEncoder(categories = cat_categories)
nom_encoder = OneHotEncoder(categories = nom_categories)

preprocessor = ColumnTransformer(transformers = [('ord',cat_encoder, cat_cols),('nom', nom_encoder, nom_cols)], remainder= 'passthrough')


X_train_encoded = preprocessor.fit_transform(X_train)
X_test_encoded = preprocessor.transform(X_test)

import xgboost as xgb
from sklearn.ensemble import RandomForestClassifier

xgb_base = xgb.XGBClassifier(
    n_estimators=120,
    max_depth=5,
    n_jobs=-1,
)

rf_base = RandomForestClassifier(
    n_estimators=120,
    max_depth=5,
    class_weight='balanced',
    n_jobs=-1,
    random_state=42,
)

base_learners =[('rf', rf_base), ('xgb', xgb_base)]

from sklearn.ensemble import StackingClassifier
from sklearn.multioutput import MultiOutputClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline

ridge_meta = LogisticRegression (penalty='l2', C=1.0, solver='lbfgs')

stack_brain = StackingClassifier(
    estimators=base_learners,
    final_estimator=ridge_meta,
    n_jobs=-1,
)

multi_target_ensemble = MultiOutputClassifier(stack_brain)

multi_target_ensemble.fit(X_train_encoded, y_train)

model_preds = multi_target_ensemble.predict_proba(X_test_encoded)

# Convert the list of predicted probabilities per target into a single NumPy array
# model_preds is a list of length 3, each of shape (200, 2)
import numpy as np
preds_array = np.array(model_preds)  # Shape: (3, 200, 2)

# Calculate and print the overall mean of the probabilities
print("Overall mean probability:", preds_array.mean())

# Print the mean predicted probability of the positive class (class 1) for each target task
for idx, target_name in enumerate(targets):
    mean_pos_prob = preds_array[idx, :, 1].mean()
    print(f"Mean predicted probability of {target_name}: {mean_pos_prob:.4f}")

from sklearn.metrics import roc_auc_score, average_precision_score
import numpy as np

# Extract the positive class probability (index 1) for each of the 3 targets
# np.array(model_preds) has shape (3, 200, 2) -> we want shape (200, 3) for the positive class probabilities
positive_probs = np.column_stack([model_preds[i][:, 1] for i in range(len(model_preds))])

# Calculate overall scores using the average='macro' or 'micro' option, or calculate per task
ROC_AUC_SCORE = roc_auc_score(y_test, positive_probs, average='macro')
AP_SCORE = average_precision_score(y_test, positive_probs, average='macro')

print(f"Macro-averaged ROC-AUC Score: {ROC_AUC_SCORE:.4f}")
print(f"Macro-averaged Average Precision Score: {AP_SCORE:.4f}")