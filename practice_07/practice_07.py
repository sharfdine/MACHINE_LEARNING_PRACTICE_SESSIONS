data = pd.read_csv("contrast_induced_aki_clinical_cohort.csv")

data.columns

data.head()

len('contrast_volume_ml')

features =["baseline_egfr", "contrast_volume_ml"]

target = ["ci_aki_developed"]

X = data[features]
y = data[target]

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
for train_index, test_index in split.split (X,y):
  X_train, X_test = X.iloc[train_index], X.iloc[test_index]
  y_train, y_test = y.iloc[train_index], y.iloc[test_index]

from sklearn.preprocessing import MinMaxScaler
scaler = MinMaxScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

from sklearn.linear_model import LogisticRegression

model=LogisticRegression(random_state=42)

model.fit(X_train_scaled, y_train)

model.score(X_test_scaled, y_test)

ci_aki_prediction=model.predict_proba(X_test_scaled)


ci_aki_prediction.mean()

from sklearn.metrics import f1_score, average_precision_score, roc_auc_score


f1_score = f1_score(y_test, model.predict(X_test_scaled))
average_precision = average_precision_score(y_test, model.predict(X_test_scaled))
roc_auc = roc_auc_score(y_test, model.predict(X_test_scaled))


print(f"F1 Score: {f1_score}")
print(f"Average Precision: {average_precision}")
print(f"ROC AUC: {roc_auc}")

from sklearn.metrics import confusion_matrix
confusion_matrix(y_test, model.predict(X_test_scaled))

threshold = 0.35


ci_aki_pred_tuned = (ci_aki_prediction[:,1] > threshold). astype(int)

from sklearn.metrics import classification_report


classification_report = classification_report(y_test, ci_aki_pred_tuned)
print(classification_report)
