import pandas as pd
import numpy as np
df = pd.read_csv('ed_septic_shock_triage.csv')

df.head()

features = ['respiratory_rate','heart_rate','spo2','temperature_c','heart_rate']
X = df[features]
y = df['septic_shock_deterioration']

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit()
for train_index, test_index in split.split (X,y):
  X_train, X_test = X.iloc[train_index], X.iloc[test_index]
  y_train, y_test = y.iloc[train_index], y.iloc[test_index]

from sklearn.preprocessing import MinMaxScaler
scaler = MinMaxScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

from sklearn.ensemble import RandomForestClassifier
model = RandomForestClassifier()
model.fit(X_train_scaled, y_train)
model.score(X_test_scaled, y_test)

septic_risk_probability = model.predict_proba(X_train_scaled)[:, 1]
print(septic_risk_probability)
septic_risk_probability.mean()

from sklearn.metrics import confusion_matrix, f1_score
# Convert probabilities to binary predictions using a 0.5 threshold
y_pred_binary = (septic_risk_probability >= 0.5).astype(int)

print("Confusion Matrix:\n", confusion_matrix(y_train, y_pred_binary))
print("F1 Score:\n", f1_score(y_train, y_pred_binary))

from sklearn.metrics import roc_auc_score
roc_auc_score(y_train, septic_risk_probability)

from sklearn.metrics import average_precision_score
average_precision_score(y_train, septic_risk_probability)

# Get septic risk probabilities for all patients in the test set
test_probabilities = model.predict_proba(X_test_scaled)[:, 1]

# Classify each patient based on the defined stratification rules
categories = []
for prob in test_probabilities:
    if prob > 0.50:
        categories.append("SEPTIC PATIENT")
    elif 0.30 < prob <= 0.50:
        categories.append("EMERGENCY CARE NEEDED")
    else:
        categories.append("NON CRITICAL PATIENT")

# Convert categories to a pandas Series to count and display the distribution
septic_code_series = pd.Series(categories)
display(septic_code_series.value_counts())

from sklearn.model_selection import GridSearchCV

param_grid = {
  'n_estimators' : [100, 200,300],
  'max_depth' : [3, 5, 8],
  'min_samples_split' : [2, 4,],
}


grid_search = GridSearchCV(model, param_grid, cv = 5)
grid_search.fit(X_train_scaled, y_train)

grid_search.best_params_

best_model = grid_search.best_estimator_
best_test_probabilities = best_model.predict_proba(X_test_scaled)[:, 1]
best_test_probabilities.mean()

best_test_preds = (best_test_probabilities >= 0.5).astype(int)
best_test_preds.mean()

from sklearn.metrics import classification_report

report = classification_report(y_test, best_test_preds)
print(report)