df = pd.read_csv('cdi_inpatient_cohort (1).csv')

df.columns

df.head()

features = ['age','antibiotic_days','ppi_usage','abx_spectrum','ward_type','wbc_count','serum_albumin','serum_creatinine']
X = df[features]
y = df['cdi_outcome']

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
for temp_index, test_index in split.split(X, y):
    X_temp, X_test = X.iloc[temp_index], X.iloc[test_index]
    y_temp, y_test = y.iloc[temp_index], y.iloc[test_index]
for train_index, val_index in split.split(X_temp, y_temp):
    X_train, X_val = X_temp.iloc[train_index], X_temp.iloc[val_index]
    y_train, y_val = y_temp.iloc[train_index], y_temp.iloc[val_index]

df.ward_type.value_counts()

ppi = ['Yes', 'No']



antibiotic_type = ['Broad_Cephalosporin','Narrow','Fluoroquinolones','Carbapenem']


ward_count = ['General_Medical','Surgical','ICU','Oncology']

from sklearn.preprocessing import OneHotEncoder, OrdinalEncoder
from sklearn.compose import ColumnTransformer

cat_cols = ['ppi_usage', 'abx_spectrum']
nom_cols = ['ward_type']

cat_categories = [ppi, antibiotic_type]
nom_categories = [ward_count]

cat_encoder = OrdinalEncoder(categories=cat_categories, handle_unknown="use_encoded_value", unknown_value=np.nan)
nom_encoder = OneHotEncoder(categories=nom_categories, handle_unknown="ignore")

preprocessor = ColumnTransformer(
    [
        ("cat", cat_encoder, cat_cols),
        ("nom", nom_encoder, nom_cols)
    ],
    remainder='passthrough'
)

X_train_encoded = preprocessor.fit_transform(X_train)
X_test_encoded = preprocessor.transform(X_test)
X_val_encoded = preprocessor.transform(X_val)

import xgboost as xgb
from sklearn.ensemble import RandomForestClassifier, StackingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.multioutput import MultiOutputClassifier
from sklearn.calibration import CalibratedClassifierCV

base_learners = [("xgb", xgb.XGBClassifier(random_state = 42, n_estimators = 100)), ("rf", RandomForestClassifier(random_state = 42, n_estimators = 100))]

meta_learner = LogisticRegression(random_state = 42, penalty = 'l2', C= 1.0)

stack = StackingClassifier(
    estimators = base_learners,
    final_estimator = meta_learner,
    cv = 5,
    n_jobs = -1,
    stack_method = 'predict_proba'
)

from sklearn.pipeline import Pipeline

pipeline = Pipeline([
    ('preprocessor', preprocessor),
    ('stacking_model', stack),
    ])

pipeline.fit(X_train, y_train)

pipeline.score(X_test, y_test)

initial_result = pipeline.predict_proba(X_test)
initial_result.mean()

val_result = pipeline.predict_proba(X_val)
val_result.mean()

from sklearn.model_selection import GridSearchCV, StratifiedKFold
from sklearn.model_selection import KFold

param_grid = {
    'stacking_model__xgb__max_depth': [4, 5],
    'stacking_model__rf__n_estimators': [80,100,120],
    'stacking_model__rf__max_depth': [3, 4, 5],
    'stacking_model__final_estimator__C': [0.1, 1.0, 0.5, 1.0]
}

cv_strategy = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

grid_search = GridSearchCV(pipeline, param_grid, cv=cv_strategy, scoring='roc_auc', n_jobs=-1)

grid_search.fit(X_train, y_train)

grid_search.score(X_test, y_test)

pre_calibration_prob = grid_search.predict_proba(X_test)
pre_calibration_prob.mean()

grid_search.best_params_

best_prob = grid_search.best_estimator_

from sklearn.base import clone

calibrated_pipeline = CalibratedClassifierCV(best_prob, cv=5, method='isotonic', n_jobs = -1)

calibrated_pipeline.fit(X_train, y_train)

non_val_prob = calibrated_pipeline.predict_proba(X_test)[:,1]
non_val_prob.mean()

val_prob = calibrated_pipeline.predict_proba(X_val)[:,1]
val_prob.mean()

from sklearn.model_selection import cross_val_predict
skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

oof_probs = cross_val_predict(clone(calibrated_pipeline), X_train, y_train, cv=skf, method="predict_proba", n_jobs=-1)[:, 1]

preds_50 = (oof_probs >=0.5).astype(int)

from sklearn.metrics import classification_report
from sklearn.metrics import confusion_matrix

confusion_matrix(y_train, preds_50)

classification_report(y_train, preds_50)

from sklearn.metrics import confusion_matrix, make_scorer
from sklearn.model_selection import TunedThresholdClassifierCV

def neg_clinical_cost(y_true, y_pred):
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
    return -(5 * fn + 1 * fp)

cost_scorer = make_scorer(neg_clinical_cost, response_method="predict")

tuned_model = TunedThresholdClassifierCV(clone(calibrated_pipeline), scoring=cost_scorer, cv=5, n_jobs=-1).fit(X_train, y_train)

tuned_model.best_threshold_

