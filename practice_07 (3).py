import pandas as pd
import numpy as np



df = pd.read_csv("inpatient_clinical_surveillance_dvt_cdi.csv")

df.head()

df.columns

"""###                                                                                                  **FEATURE ENGINEERING AND DEFINITIONS OF FEATURES**"""

features = ['gender','admission_ward','primary_antibiotic_class','frailty_score_tier','mobility_status','bowel_frequency_tier','ppi_exposure_duration','prior_cdi_history','immunosuppressed_flag','mechanical_ventilation', 'active_malignancy_flag', 'prior_vte_history','recent_surgery_trauma','age','bmi_kg_m2', 'charlson_comorbidity_index','abx_duration_days','nephrotoxic_drug_count','serum_albumin_g_dl','wbc_count_k_ul','baseline_creatinine_mg_dl','d_dimer_mg_l','platelet_count_k_ul','systolic_bp_mmhg']
X = df[features]

targets = ['cdi_infection_flag','dvt_vte_risk_flag','readmission_30d_flag','acute_kidney_injury_flag']
y = df[targets]

"""## **SPLITTING OF DATA**"""

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit(n_splits = 1, random_state = 42, test_size = 0.2)
for train_index, test_index in split.split (X,y):
  X_train, X_test = X.iloc[train_index], X.iloc[test_index]
  y_train, y_test = y.iloc[train_index], y.iloc[test_index]

df.primary_antibiotic_class.value_counts()

"""# **FEATURE PRE PROCESSING**"""

ward_count = ['General Medical','Surgical','Oncology','Geriatric Care','ICU Stepdown']

frailty_status = ['Fit / Robust','Mild Frailty','Moderate Frailty','Severe Frailty']

mobility_count = ['Independent','Assisted','Bedbound']

bowel_status = ['Normal (1-2/day)','Elevated (3-5/day)','Frequent (>5/day)']

ppi_exposure_duration = ['Short-term (<7d)','Prolonged (>=7d)']

cdi_status = ['Yes','No']

immunosuppression_status = ['Yes','No']

gender_count = ['Male','Female']


antibiotic_count = ['Macrolide', 'Penicillin/BLI','Fluoroquinolone','Carbapenem','Cephalosporin (3rd/4th Gen)']
ventilation_status = ['Yes','No']
malignancy_status = ['Yes','No']
vte_status = ['Yes','No']
surgery_status = ['Yes','No']

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OrdinalEncoder, OneHotEncoder

ordinal_encoder = OrdinalEncoder(categories = [frailty_status,mobility_count,bowel_status,ppi_exposure_duration,cdi_status,immunosuppression_status])

# Fixed 'prior_vte_status' to match the dataset column name 'prior_vte_history'
cat_cols = ['frailty_score_tier','mobility_status','bowel_frequency_tier','ppi_exposure_duration','prior_cdi_history','immunosuppressed_flag','mechanical_ventilation','active_malignancy_flag','prior_vte_history','recent_surgery_trauma']

cat_categories = [frailty_status,mobility_count,bowel_status,ppi_exposure_duration,cdi_status,immunosuppression_status,ventilation_status,malignancy_status,vte_status,surgery_status ]

nom_cols = ['gender','admission_ward','primary_antibiotic_class']

nom_categories = [gender_count, ward_count, antibiotic_count]

cat_encoder = OrdinalEncoder(categories = cat_categories, handle_unknown="use_encoded_value", unknown_value = -1)
nom_encoder = OneHotEncoder(categories = nom_categories, handle_unknown = "ignore")

preprocessor = ColumnTransformer([
    ('ord', cat_encoder, cat_cols),
    ('nom', nom_encoder, nom_cols)], remainder= 'passthrough'
)

X_train_encoded = preprocessor.fit_transform(X_train)
X_test_encoded = preprocessor.transform(X_test)

"""## **ENSEMBLE ENGINEERING**"""

import xgboost as xgb
from sklearn.ensemble import RandomForestClassifier, StackingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline
from sklearn.multioutput import MultiOutputClassifier

base_learners = [("rf", RandomForestClassifier(n_estimators=100, random_state=42, class_weight = 'balanced')), ("xgb", xgb.XGBClassifier(random_state=42, n_estimators=100))]

meta_learner = LogisticRegression(random_state = 42, penalty='l2', C=1.0)

stacking_model = StackingClassifier(
    estimators = base_learners,
    final_estimator = meta_learner,
    stack_method='predict_proba',
    n_jobs = -1
)

# Wrap the single-target StackingClassifier to support multiple output labels
multi_target_model = MultiOutputClassifier(stacking_model, n_jobs=-1)

model_pipeline = Pipeline (steps = [('preprocessor', preprocessor), ('stacking_model', multi_target_model)])

model_pipeline.fit(X_train, y_train)

model_pipeline.score(X_test, y_test)

model_prediction = model_pipeline.predict_proba(X_test)
print("Model Prediction:", model_prediction)

"""## **TUNING OF THE HYPERPARAMETERS**"""

from sklearn.model_selection import GridSearchCV, KFold

# Correct nested parameter pathing:
# pipeline step ('stacking_model') -> MultiOutputClassifier wrapper ('estimator') -> stacking components
param_grid = {
    'stacking_model__estimator__rf__n_estimators': [80, 100,200],
    'stacking_model__estimator__rf__max_depth': [3,4,5,6],
    'stacking_model__estimator__rf__min_samples_leaf': [2, 4, 8],
    'stacking_model__estimator__xgb__n_estimators': [80,120,200],
    'stacking_model__estimator__xgb__max_depth': [2,3,4],
    'stacking_model__estimator__xgb__learning_rate': [0.03, 0.05, 0.1],
    'stacking_model__estimator__final_estimator__C': [0.1,0.5, 1.0, 5.0],
}

# Use standard KFold because StratifiedKFold does not support multi-output indicators
cv_strategy = KFold(n_splits=3, shuffle=True, random_state=42)

# Updated scoring metric to 'roc_auc_ovr' to support multi-label evaluation
grid_search = GridSearchCV(model_pipeline, param_grid, cv=cv_strategy, scoring='roc_auc_ovr', n_jobs=-1)

grid_search.fit(X_train, y_train)

grid_search.best_estimator_
best_tuned_model = grid_search.best_estimator_

grid_search.best_score_

grid_search.best_params_

"""## **MODEL PERFORMANCES**"""

probs_list = best_tuned_model.predict_proba(X_test)
y_prob_matrix = np.array([probs[:, 1] for probs in probs_list])
print("Probability Matrix Shape:", y_prob_matrix.shape)

# Transpose y_prob_matrix to match the shape of y_test (from (4, 300) to (300, 4))
from sklearn.metrics import roc_auc_score, average_precision_score
macro_roc_auc_ovr = roc_auc_score(y_test, y_prob_matrix.T, multi_class="ovr", average="macro")
print("Macro ROC AUC (OVR):", macro_roc_auc_ovr)

macro_precision_ovr = average_precision_score(y_test, y_prob_matrix.T, average="macro")
print("Macro Precision (OVR):", macro_precision_ovr)