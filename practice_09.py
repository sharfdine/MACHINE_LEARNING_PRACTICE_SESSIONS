df = pd.read_csv('cdi_inpatient_cohort (1).csv')

df.columns

df.head()

features = ['age','antibiotic_days','ppi_usage','abx_spectrum','ward_type','wbc_count','serum_albumin','serum_creatinine']
X = df[features]
y = df['cdi_outcome']

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
for train_index, test_index in split.split(X, y):
    X_train, X_test = X.iloc[train_index], X.iloc[test_index]
    y_train, y_test = y.iloc[train_index], y.iloc[test_index]

df.ward_type.value_counts()

ppi = ['Yes', 'No']



antibiotic_type = ['Broad_Cephalosporin','Narrow','Fluoroquinolones','Carbapenem']


ward_count = ['General_Medical','Surgical','ICU','Oncology']

from sklearn.preprocessing import OneHotEncoder, OrdinalEncoder
from sklearn.compose import ColumnTransformer

cat_cols = ['ppi_usage', 'abx_spectrum']
nom_cols = ['ward_type']

cat_categories = [ppi, antibiotic_type]
nom_categories = [ward_count]

cat_encoder = OrdinalEncoder(categories=cat_categories, handle_unknown="use_encoded_value", unknown_value=np.nan)
nom_encoder = OneHotEncoder(categories=nom_categories, handle_unknown="ignore")

preprocessor = ColumnTransformer(
    [
        ("cat", cat_encoder, cat_cols),
        ("nom", nom_encoder, nom_cols)
    ],
    remainder='passthrough'
)

X_train_encoded = preprocessor.fit_transform(X_train)
X_test_encoded = preprocessor.transform(X_test)

import xgboost as xgb
from sklearn.ensemble import RandomForestClassifier, StackingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.multioutput import MultiOutputClassifier

base_learners = [("xgb", xgb.XGBClassifier(random_state = 42, n_estimators = 100)), ("rf", RandomForestClassifier(random_state = 42, n_estimators = 100))]

meta_learner = LogisticRegression(random_state = 42, penalty = 'l2', C= 1.0)

stack = StackingClassifier(
    estimators = base_learners,
    final_estimator = meta_learner,
    cv = 5,
    n_jobs = -1,
    stack_method = 'predict_proba'
)

from sklearn.pipeline import Pipeline

pipeline = Pipeline([
    ('preprocessor', preprocessor),
    ('stacking_model', stack),])

pipeline.fit(X_train, y_train)

pipeline.score(X_test, y_test)

initial_result = pipeline.predict_proba(X_test)
initial_result.mean()

from sklearn.model_selection import GridSearchCV, KFold

param_grid = {
    'stacking_model__xgb__n_estimators': [100, 200, 300],
    'stacking_model__xgb__learning_rate': [0.01, 0.1, 0.2],
    'stacking_model__xgb__max_depth': [3, 4, 5],
    'stacking_model__rf__n_estimators': [80,100,120],
    'stacking_model__rf__max_depth': [3, 4, 5],
    'stacking_model__meta_learner__C': [0.1, 1.0, 10.0]
}

cv_strategy = KFold(n_splits=5, shuffle=True, random_state=42)

grid_search = GridSearchCV(pipeline, param_grid, cv=cv_strategy, scoring='roc_auc_ovr', n_jobs=-1)

