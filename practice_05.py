import pandas as pd
import numpy as np

df = pd.read_csv("hospital_cdi_surveillance.csv")

df.head()

df.immunosuppressed_flag.value_counts()

features = ['frailty_score_tier','bowel_frequency_tier','ppi_exposure_duration','prior_cdi_history','immunosuppressed_flag','mechanical_ventilation','age','serum_albumin_g_dl','wbc_count_k_ul','antibiotic_duration_days','serum_creatinine_mg_dl']

X = df[features]
y = df['developed_cdi']

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit(n_splits = 1, test_size = 0.2, random_state = 42)
for train_index, test_index in split.split (X,y):
  X_train, X_test = X.iloc[train_index], X.iloc[test_index]
  y_train, y_test = y.iloc[train_index], y.iloc[test_index]

from sklearn.preprocessing import OrdinalEncoder
from sklearn.compose import ColumnTransformer

frailty_score = ['Mild Frailty',
'Fit / Robust',
'Moderate Frailty',
'Severe Frailty',]

bowel_status = ['Normal (1-2/day)',
'Elevated (3-5/day)',
'Frequent (>5/day)',]

ppi_exposure = ['Prolonged (>=7d)',
'Short-term (<7d)', ]

cdi_status =['Yes','No',]

immunosuppresion_status =['Yes', 'No',]

ventilation_status = ['Yes','No',]

cat_cols = ['frailty_score_tier','bowel_frequency_tier','ppi_exposure_duration','prior_cdi_history','immunosuppressed_flag','mechanical_ventilation']

decided_categories = [frailty_score, bowel_status, ppi_exposure, cdi_status, immunosuppresion_status, ventilation_status]

# Configure the OrdinalEncoder to preserve NaN values instead of raising an error
encoder = OrdinalEncoder(
    categories=decided_categories,
    handle_unknown='use_encoded_value',
    unknown_value=np.nan
)

preprocessor = ColumnTransformer(transformers = [('cat', encoder, cat_cols)], remainder = 'passthrough')

X_train_encoded = preprocessor.fit_transform(X_train)
X_test_encoded = preprocessor.transform(X_test)

import xgboost as xgb

model = xgb.XGBClassifier(random_state = 42, use_label_encode = False)


model.fit(X_train_encoded, y_train)
model.score(X_test_encoded, y_test)

cdi_probability = model.predict_proba(X_test_encoded)[:,1]
cdi_probability.mean()

from sklearn.model_selection import GridSearchCV


param_grid = {
    'max_depth': [2,3,4,6],
    'subsample': [0.6,0.8,1.0],
    'learning_rate': [0.01, 0.05,0.1],
    'reg_lambda': [1.0,3.0,5.0],
    'n_estimators': [100,200,300],
    'colsample_bytree': [0.6,0.8,1.0],
    'colsample_bylevel': [0.6,0.8,1.0],
}


grid_search = GridSearchCV(model, param_grid, cv = 5)
grid_search.fit(X_train_encoded, y_train)

grid_search.best_score_

tuned_model = grid_search.best_estimator_

cdi_probabilities = tuned_model.predict_proba(X_test_encoded)[:,1]


cdi_probabilities.mean()

categories = []



for prob in cdi_probabilities:

  if prob >0.80:
    categories.append("CDI INFECTION CASE")
  if prob >=0.60:
    categories.append("EXPECTED CDI INFECTION")
  if prob >= 0.40:
    categories.append("CHECK FOR CDI INFECTION")
  else:
    categories.append("SAFE TO DISCHARGE")

cdi_series = pd.Series(categories)

display(cdi_series.value_counts())

from sklearn.metrics import classification_report

y_pred = tuned_model.predict(X_test_encoded)

report = classification_report(y_test, y_pred)

print(report)

from sklearn.metrics import roc_auc_score, average_precision_score
ROC_AUC = roc_auc_score(y_test, cdi_probabilities)
PR_AUC = average_precision_score(y_test, cdi_probabilities)

print(f"ROC AUC: {ROC_AUC}")
print(f"PR AUC: {PR_AUC}")