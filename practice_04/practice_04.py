import pandas as pd
import numpy as np

df = pd.read_csv('post_pci_categorical_readmission.csv')

df.head()

df['dapt_adherence'].value_counts()

df['ckd_stage'].value_counts()

df['stent_type'].value_counts()

df['lvef_category'].value_counts()

df['anemia_status'].value_counts()

features = ['anemia_status', 'lvef_category', 'ckd_stage', 'dapt_adherence', 'stent_type','prior_mi', 'diabetes_mellitus', 'discharge_systolic_bp',	'discharge_heart_rate',	'stents_implanted','age']
X = df[features]
y = df['readmitted_30d']

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
for train_index, test_index in split.split(df, df["readmitted_30d"]):
    X_train, X_test = X.iloc[train_index], X.iloc[test_index]
    y_train, y_test = y.iloc[train_index], y.iloc[test_index]

anemia_order = [
	'Normal',
	'Mild',
	'Moderate to Severe',
]

lvef_order = [
'Preserved (>=50%)',
'Mildly Reduced (41-49%)',
'Moderately Reduced (30-40%)',
'Severely Reduced (<30%)',]

stent_order = ['Drug-Eluting Stent (DES)',
'Bare-Metal Stent (BMS)',]

ckd_order = ['Stage 1-2 (Normal/Mild)',
'Stage 4-5 (Severe/Failure)',
'Stage 3 (Moderate)',]

dapt_order =['Strict', 'Poor',]

dm_status = ['Yes', 'No',]
past_mi = ['Yes','No']

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OrdinalEncoder

# 1. Reset X_train and X_test to clean, unmodified states to clear previously mutated numeric floats
X_train = X.iloc[train_index].copy()
X_test = X.iloc[test_index].copy()

cat_cols = ['anemia_status', 'lvef_category', 'ckd_stage', 'dapt_adherence', 'stent_type', 'diabetes_mellitus', 'prior_mi']
categories_decided = [anemia_order, lvef_order, ckd_order, dapt_order, stent_order, dm_status, past_mi]

# 2. Build preprocessor ensuring remainder='passthrough' is passed as an argument
preprocessor = ColumnTransformer(
    transformers=[
        ("cat", OrdinalEncoder(categories=categories_decided), cat_cols)
    ],
    remainder='passthrough'
)

X_train_encoded = preprocessor.fit_transform(X_train)
X_test_encoded = preprocessor.transform(X_test)

import xgboost as xgb

# Instantiate the XGBoost Classifier object rather than using the raw module
model = xgb.XGBClassifier(random_state=42, use_label_encoder=False, eval_metric='logloss')

# Train the model
model.fit(X_train_encoded, y_train)

# Score the model using the correctly spelled encoded test array
test_accuracy = model.score(X_test_encoded, y_test)
print(f"XGBoost Test Accuracy: {test_accuracy:.4f}")

readmission_probability = model.predict_proba(X_test_encoded)
readmission_probability.mean()

from sklearn.metrics import f1_score,roc_auc_score,average_precision_score
F1_score = f1_score(y_test, model.predict(X_test_encoded))
ROC_AUC = roc_auc_score(y_test, model.predict_proba(X_test_encoded)[:,1])
AP = average_precision_score(y_test, model.predict_proba(X_test_encoded)[:,1])
print(f'F1 Score: {F1_score}\nROC AUC Score: {ROC_AUC}\nAverage Precision Score: {AP}')

from sklearn.model_selection import GridSearchCV

param_grid ={
    'max_depth': [2,3,4,6],
    'subsample': [0.6,0.8,1.0],
}

grid_search = GridSearchCV(model, param_grid, cv=5)

grid_search.fit(X_train_encoded, y_train)

best_model = grid_search.best_estimator_

final_probabilities = best_model.predict_proba(X_test_encoded)
final_probabilities.mean()

grid_search.best_score_

# since we are going to categorise patients either this has a chance of readmission or not so



best_readmission_chances = (final_probabilities >= 0.50).astype(int)
best_readmission_chances.mean()

# since the system will get the patient vitals and findings and will decide the status of patient readmission



readmission_probability = model.predict_proba(X_test_encoded)[:, 1]
categories = []

for prob in readmission_probability:
  if prob >0.70:
    categories.append("Readmission")

  elif prob >=0.50:
    categories.append("Expected Readmission")
  else:
    categories.append("No Readmission")

readmission_series = pd.Series(categories)
display(readmission_series.value_counts())

from sklearn.metrics import classification_report
best_model_predictions = best_model.predict(X_test_encoded)
report = classification_report(y_test, best_model_predictions)
print(report)
