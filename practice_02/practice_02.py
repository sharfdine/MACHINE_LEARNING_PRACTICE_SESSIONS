import pandas as pd
import numpy as np
df = pd.read_excel('heart_failure_clinical_records_ml_task.xlsx')

df.head()

"""We are going to create a random forest classifier to classify the patients cominig in ER on the basis of their demographics and past medical histroy to assign them a status.

Here,

Emergency refers to care within 5 minutes
Immediate refers to care within 10 minutes
Urgent refers to care within 30 minutes
"""

# Redefining X and y to ensure it contains the DataFrame and not the overridden regex scalar
features = ['sex','smoking','age','diabetes','high_blood_pressure']
X = df[features]
y = df['DEATH_EVENT']

from sklearn.model_selection import StratifiedShuffleSplit
split = StratifiedShuffleSplit (n_splits = 1, test_size = 0.2, random_state=42)
for train_index, test_index in split.split (X,y):
  X_train, X_test = X.iloc[train_index], X.iloc[test_index]
  y_train, y_test = y.iloc[train_index], y.iloc[test_index]

from sklearn.preprocessing import MinMaxScaler
Scaler = MinMaxScaler()
X_train_scaled = Scaler.fit_transform(X_train)
X_test_scaled = Scaler.transform(X_test)

from sklearn.ensemble import RandomForestClassifier
model = RandomForestClassifier()
model.fit(X_train_scaled, y_train)
model.score(X_test_scaled, y_test)

predicted_probability = model.predict_proba(X_test_scaled)
X_test_scaled.mean()

from sklearn.metrics import confusion_matrix
model_prediction = model.predict(X_test_scaled)
confusion_matrix(y_test,model_prediction)

from sklearn.metrics import accuracy_score, precision_score, recall_score, roc_auc_score, average_precision_score
accuracy_score(y_test,model_prediction)

precision_score(y_test,model_prediction)

recall_score(y_test,model_prediction)

roc_auc_score(y_test,model_prediction)

average_precision_score(y_test,model_prediction)

Triage = []
# Loop through the prediction probabilities
for predicted_probability in model.predict_proba(X_test_scaled):
    # Extract the probability for class 1 (risk of DEATH_EVENT)
    prob_death = predicted_probability[1]

    if prob_death >= 0.50:
        Triage.append('Emergency')
    elif prob_death >= 0.30 and prob_death < 0.50:
        Triage.append('Immediate')
    else:
        Triage.append('Urgent')

# Display the first few results
print(Triage)
Triage_series = pd.Series(Triage)
Triage_series.value_counts()

from sklearn.model_selection import cross_val_score
scores = cross_val_score(model, X_test_scaled, y_test, cv=10)
print(scores)
scores.mean()

from sklearn.model_selection import GridSearchCV
param_grid = {
    'n_estimators':[100,200,500,1000]
}

grid_search = GridSearchCV(estimator=model, param_grid=param_grid, cv=5)
grid_search.fit(X_train_scaled, y_train)

print('Best Parameters:', grid_search.best_params_)
print('Best Score:', grid_search.best_score_)
best_model = grid_search.best_estimator_
best_model.score(X_test_scaled, y_test)
best_model.predict(X_test_scaled)
accuracy_score(y_test, best_model.predict(X_test_scaled))

import pandas as pd

Triage_optimized = []
# Get probabilities using the optimized best_model
optimized_probabilities = best_model.predict_proba(X_test_scaled)

for prob_pair in optimized_probabilities:
    # Extract probability of class 1 (DEATH_EVENT)
    prob_death = prob_pair[1]

    if prob_death >= 0.50:
        Triage_optimized.append('Emergency')
    elif prob_death >= 0.30 and prob_death < 0.50:
        Triage_optimized.append('Immediate')
    else:
        Triage_optimized.append('Urgent')

# Convert to a Series and display the distribution
triage_opt_series = pd.Series(Triage_optimized)
print("Optimized Triage Category Distribution:")
display(triage_opt_series.value_counts())
