cat_cols = ['ppi_usage', 'abx_spectrum']
nom_cols = ['ward_type']

cat_encoder = OrdinalEncoder(
    categories=[ppi, antibiotic_type],
    handle_unknown='use_encoded_value',
    unknown_value=np.nan
)
