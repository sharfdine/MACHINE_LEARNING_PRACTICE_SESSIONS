def calculate_psi(reference, target, num_buckets=10):
    # Remove missing values for calculation
    reference = reference.dropna()
    target = target.dropna()

    # Use quantiles from the reference dataset to define boundaries
    percentiles = np.linspace(0, 100, num_buckets + 1)
    buckets = np.percentile(reference, percentiles)
    buckets[0] = -np.inf
    buckets[-1] = np.inf

    # Calculate counts in each bucket
    ref_counts, _ = np.histogram(reference, bins=buckets)
    target_counts, _ = np.histogram(target, bins=buckets)

    # Convert counts to fractions (probabilities)
    ref_pct = ref_counts / len(reference)
    target_pct = target_counts / len(target)

    # Replace 0s with a tiny decimal value to avoid division by zero or log(0) issues
    ref_pct = np.where(ref_pct == 0, 0.0001, ref_pct)
    target_pct = np.where(target_pct == 0, 0.0001, target_pct)

    # Calculate PSI formula: (Actual_i - Expected_i) * ln(Actual_i / Expected_i)
    psi_value = np.sum((target_pct - ref_pct) * np.log(target_pct / ref_pct))
    return psi_value

