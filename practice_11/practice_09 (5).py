def validate_input_schema(df):
    required_cols = ["age", "antibiotic_days", "wbc_count", "serum_albumin", "serum_creatinine"]

    # Check if all columns exist
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        return False, f"Missing columns: {missing}"

    # Check for negative/impossible numbers
    if (df["age"] <= 0).any() or (df["wbc_count"] <= 0).any():
        return False, "Age and WBC count must be greater than 0"

    return True, "Valid"

def generate_drift_report(ref_df, new_df, cols):
    report = {}
    for col in cols:
        # Compare training distribution vs new data distribution (KS Test)
        stat, p_value = ks_2samp(ref_df[col].dropna(), new_df[col].dropna())
        report[col] = {
            "drift_detected": bool(p_value < 0.05),
            "p_value": round(p_value, 4)
        }
    return report



